export function categoryIcon(name: string, fallback: LucideIcon = House): LucideIcon {
  const normalized = name.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
  return rules.find(([pattern]) => pattern.test(normalized))?.[1] ?? fallback;
}
